typedef enum {
	FIR_COEFF_MODE,
	FIR_SAMPLE_MODE
}fir_state_t;

volatile fir_state_t fir_state = FIR_COEFF_MODE;

// 256 bytes = 128 samples
int8_t uart_tx_buf[UART_BLOCK_SIZE];
int8_t uart_rx_buf[UART_BLOCK_SIZE];

// 128 samples to FIR
int16_t spi_rx_buf[SPI_BLOCK_SIZE];
int16_t spi_tx_buf[SPI_BLOCK_SIZE];


void reset_fpga() {
  HAL_GPIO_WritePin(FIR_RST_N_GPIO_Port, FIR_RST_N_Pin, GPIO_PIN_RESET);
  HAL_Delay(1);
  HAL_GPIO_WritePin(FIR_RST_N_GPIO_Port, FIR_RST_N_Pin, GPIO_PIN_SET);
}

void load_coeffcients() {
	HAL_UART_Receive_DMA(&huart2, (uint8_t*)&uart_rx_buf, UART_BLOCK_SIZE);
}

void spi_transfer_coefficients() {
	HAL_GPIO_WritePin(FIR_MODE_GPIO_Port, FIR_MODE_Pin, GPIO_PIN_RESET);
	for (int i = 0; i < SPI_BLOCK_SIZE; i++) {
		HAL_GPIO_WritePin(CS_N_GPIO_Port, CS_N_Pin, GPIO_PIN_RESET);
		HAL_SPI_TransmitReceive(&hspi2, (uint8_t *)&spi_tx_buf[i], (uint8_t *)&spi_rx_buf[i], 1, HAL_MAX_DELAY);
		HAL_GPIO_WritePin(CS_N_GPIO_Port, CS_N_Pin, GPIO_PIN_SET);
	}
	HAL_GPIO_WritePin(FIR_MODE_GPIO_Port, FIR_MODE_Pin, GPIO_PIN_SET);
	fir_state = FIR_SAMPLE_MODE;
	memcpy(uart_tx_buf, spi_rx_buf, sizeof(uart_tx_buf));
	HAL_UART_Transmit_DMA(&huart2, (uint8_t *)&uart_tx_buf, UART_BLOCK_SIZE);

}

void spi_transfer_samples() {
	HAL_GPIO_WritePin(FIR_MODE_GPIO_Port, FIR_MODE_Pin, GPIO_PIN_SET);
	for (int i = 0; i < SPI_BLOCK_SIZE; i++) {
		HAL_GPIO_WritePin(CS_N_GPIO_Port, CS_N_Pin, GPIO_PIN_RESET);
		HAL_SPI_TransmitReceive(&hspi2, (uint8_t *)&spi_tx_buf[i], (uint8_t *)&spi_rx_buf[i], 1, HAL_MAX_DELAY);
		HAL_GPIO_WritePin(CS_N_GPIO_Port, CS_N_Pin, GPIO_PIN_SET);
	}
	memcpy(uart_tx_buf, spi_rx_buf, sizeof(uart_tx_buf));
	HAL_UART_Transmit_DMA(&huart2, (uint8_t *)&uart_tx_buf, UART_BLOCK_SIZE);
}


